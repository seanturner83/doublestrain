"""Python locks as data: uv.lock, poetry.lock (+ pyproject), Pipfile.lock and
pip-compile requirements, into packages, edges and dev/runtime."""
import json

from doublestrain import osv, pylock
from doublestrain.judges import depgraph
from doublestrain.judges.usage import _import_re, copies_note, usage_summary

H1, H2 = "a" * 64, "b" * 64


def test_uv_lock(tmp_path):
    (tmp_path / "uv.lock").write_text(f'''
version = 1
[[package]]
name = "app"
version = "0.1.0"
source = {{ editable = "." }}
dependencies = [{{ name = "fastapi" }}]
[package.optional-dependencies]
llm = [{{ name = "transformers" }}]
dev = [{{ name = "pytest" }}]
[package.dev-dependencies]
lint = [{{ name = "ruff" }}]

[[package]]
name = "fastapi"
version = "0.110.0"
source = {{ registry = "https://pypi.org/simple" }}
dependencies = [{{ name = "starlette" }}]
wheels = [{{ url = "https://files.pythonhosted.org/f/fastapi-0.110.0-py3-none-any.whl", hash = "sha256:{H1}" }}]

[[package]]
name = "Starlette"
version = "0.36.3"
source = {{ registry = "https://pypi.org/simple" }}
sdist = {{ url = "https://files.pythonhosted.org/s/starlette-0.36.3.tar.gz", hash = "sha256:{H2}" }}

[[package]]
name = "transformers"
version = "4.40.0"
source = {{ registry = "https://pypi.org/simple" }}

[[package]]
name = "pytest"
version = "8.0.0"
source = {{ registry = "https://pypi.org/simple" }}

[[package]]
name = "ruff"
version = "0.4.0"
source = {{ registry = "https://pypi.org/simple" }}

[[package]]
name = "localpkg"
version = "0.0.1"
source = {{ path = "../localpkg" }}
''')
    lock = pylock.load(tmp_path)
    assert lock.kind == "uv.lock" and "localpkg@0.0.1" not in lock.pkgs           # no published version
    assert lock.edges["fastapi@0.110.0"] == ("starlette@0.36.3",)
    assert lock.pkgs["starlette@0.36.3"].hashes == (H2,)
    assert lock.runtime() == {"fastapi@0.110.0", "starlette@0.36.3", "transformers@4.40.0"}  # extras are prod
    assert lock.is_dev("pytest@8.0.0") and lock.is_dev("ruff@0.4.0")
    deps = {(d.name, d.direct, d.dev) for d in osv.find_deps(tmp_path)[0]}
    assert ("starlette", False, False) in deps and ("fastapi", True, False) in deps and ("ruff", True, True) in deps
    g = depgraph.load(tmp_path, "pypi")
    assert depgraph.describe(g, depgraph.chains(g, "starlette")[0]).startswith("app -> fastapi@0.110.0 -> starlette@0.36.3")


def test_poetry_lock_with_pyproject(tmp_path):
    (tmp_path / "pyproject.toml").write_text('''
[tool.poetry.dependencies]
python = "^3.11"
llama-index-core = "^0.10"
gradio = {version = "^4", optional = true}
[tool.poetry.extras]
ui = ["gradio"]
[tool.poetry.group.dev.dependencies]
mypy = "^1"
''')
    (tmp_path / "poetry.lock").write_text(f'''
[[package]]
name = "llama-index-core"
version = "0.10.0"
optional = false
files = [{{file = "llama_index_core-0.10.0-py3-none-any.whl", hash = "sha256:{H1}"}}]
[package.dependencies]
nltk = ">=3.8"
[[package]]
name = "nltk"
version = "3.8.1"
optional = false
files = []
[[package]]
name = "gradio"
version = "4.0.0"
optional = true
files = []
[[package]]
name = "mypy"
version = "1.9.0"
optional = false
files = []
[metadata]
lock-version = "2.0"
''')
    lock = pylock.load(tmp_path)
    assert lock.kind == "poetry.lock"
    assert lock.runtime() == {"llama-index-core@0.10.0", "nltk@3.8.1", "gradio@4.0.0"}
    assert lock.is_dev("mypy@1.9.0") and lock.pkgs["llama-index-core@0.10.0"].files[0][1] == H1


def test_pipfile_lock(tmp_path):
    (tmp_path / "Pipfile.lock").write_text(json.dumps({
        "default": {"django": {"version": "==4.2.0", "hashes": [f"sha256:{H1}"]},
                    "localthing": {"path": "."}},
        "develop": {"pytest": {"version": "==8.0.0"}}}))
    lock = pylock.load(tmp_path)
    assert set(lock.pkgs) == {"django@4.2.0", "pytest@8.0.0"} and lock.is_dev("pytest@8.0.0")
    assert lock.pkgs["django@4.2.0"].hashes == (H1,)


def test_pip_compile_requirements_give_a_graph(tmp_path):
    (tmp_path / "requirements.txt").write_text(f'''#
# This file is autogenerated by pip-compile
#
click==8.1.7 \\
    --hash=sha256:{H1}
    # via flask
flask==3.0.3
    # via -r requirements.in
jinja2==3.1.4
    # via
    #   flask
    #   other-pkg
other-pkg==1.0
    # via -r requirements.in
''')
    (tmp_path / "requirements-dev.txt").write_text("pytest==8.0.0\n    # via -r requirements-dev.in\n")
    lock = pylock.load(tmp_path)
    assert lock.kind == "requirements" and lock.pkgs["click@8.1.7"].hashes == (H1,)
    assert lock.prod_roots == {"flask@3.0.3", "other-pkg@1.0"} and lock.dev_roots == {"pytest@8.0.0"}
    assert set(lock.edges["flask@3.0.3"]) == {"click@8.1.7", "jinja2@3.1.4"}
    assert lock.runtime() == {"flask@3.0.3", "click@8.1.7", "jinja2@3.1.4", "other-pkg@1.0"}


def test_plain_pins_are_all_direct(tmp_path):
    (tmp_path / "requirements.txt").write_text("Flask==3.0.3\nPyYAML[extra]==6.0.1 ; python_version > '3'\nrequests>=2\n")
    lock = pylock.load(tmp_path)
    assert set(lock.pkgs) == {"flask@3.0.3", "pyyaml@6.0.1"} and lock.runtime() == set(lock.pkgs)
    assert {d.name for d in osv.find_deps(tmp_path)[0] if d.direct} == {"flask", "pyyaml"}


def test_python_imports_and_copies(tmp_path):
    r = _import_re("pypi", "PyYAML", "")
    assert all(r.search(s) for s in ["import yaml", "import os, yaml as y", "from yaml.loader import X"])
    assert not any(r.search(s) for s in ["import yamllint", "# import yaml", "from yamlx import a"])
    assert _import_re("pypi", "llama-index-llms-ollama", "").search("from llama_index.llms.ollama import Ollama")
    assert pylock.import_names("google-cloud-storage")[-1] == "google.cloud.storage"
    # two installed versions: the copies note works for pip too
    (tmp_path / "uv.lock").write_text('''
[[package]]
name = "app"
version = "0"
source = { virtual = "." }
dependencies = [{ name = "a" }, { name = "urllib3", version = "2.2.0" }]
[[package]]
name = "a"
version = "1"
source = { registry = "https://pypi.org/simple" }
dependencies = [{ name = "urllib3", version = "1.26.0" }]
[[package]]
name = "urllib3"
version = "1.26.0"
source = { registry = "https://pypi.org/simple" }
[[package]]
name = "urllib3"
version = "2.2.0"
source = { registry = "https://pypi.org/simple" }
''')
    (tmp_path / "main.py").write_text("import urllib3\n")
    note = copies_note(str(tmp_path), "pypi", "urllib3", "1.26.0")
    assert "this advisory row is about 1.26.0" in note and "required by: a@1" in note
    assert "main.py:1" in usage_summary(str(tmp_path), "pypi", "urllib3", version="1.26.0").text
